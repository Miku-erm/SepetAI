export const seedProducts = rows.map(
  (
    [
      brand,
      model,
      price,
      stock,
      cpu,
      gpu,
      ramGb,
      storageGb,
      screenSize,
      refreshRate,
      weightKg,
      batteryHours,
      purposeTags,
    ],
    i,
  ) => ({
    id: `p${String(i + 1).padStart(2, "0")}`,
    brand,
    model,
    category: "laptop",
    price,
    stock,
    cpu,
    gpu,
    ramGb,
    storageGb,
    screenSize,
    refreshRate,
    weightKg,
    batteryHours,
    purposeTags: JSON.stringify(purposeTags),
    color: ["sage", "sand", "slate", "lavender"][i % 4],
    description: `${brand} ${model}, ${ramGb} GB RAM ve ${storageGb} GB SSD ile günlük ihtiyaçlarına eşlik eder. ${weightKg} kg ağırlık ve demo koşullarında ${batteryHours} saate kadar pil süresi. Kurgusal üniversite projesi ürünü; teknik bilgiler satış vaadi değildir.`,
  }),
);
export async function seedDatabase(db: PrismaClient) {
  // Upserts make reseeding repeatable without deleting the demo cart.
  await db.$transaction(
    seedProducts.map((p) =>
      db.product.upsert({ where: { id: p.id }, create: p, update: p }),
    ),
  );
}
